#!/usr/bin/env bash
# Bring up and configure the Magpie dev stack. Safe to re-run (every step checks before it creates).
#
#   dev/bootstrap.sh
#
# Writes credentials to dev/.env.local (gitignored, chmod 600). Prints a summary at the end.
set -euo pipefail

DEV_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="$DEV_DIR/.env.local"
COMPOSE=(docker compose -f "$DEV_DIR/docker-compose.yml")
ND=http://127.0.0.1:4533
LD=http://127.0.0.1:8686

say()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
ok()   { printf '    \033[32mok\033[0m  %s\n' "$*"; }
warn() { printf '    \033[33mwarn\033[0m %s\n' "$*"; }
die()  { printf '\033[31merror:\033[0m %s\n' "$*" >&2; exit 1; }

for c in docker curl jq openssl; do command -v $c >/dev/null || die "$c is required"; done

genpw() { openssl rand -base64 24 | tr -dc 'A-Za-z0-9' | cut -c1-20; }

# ------------------------------------------------------------------ credentials file
[[ -f "$ENV_FILE" ]] && set -a && . "$ENV_FILE" && set +a
NAVIDROME_URL=$ND
NAVIDROME_ADMIN_USER=${NAVIDROME_ADMIN_USER:-admin}
NAVIDROME_ADMIN_PASSWORD=${NAVIDROME_ADMIN_PASSWORD:-$(genpw)}
NAVIDROME_LISTENER_USER=${NAVIDROME_LISTENER_USER:-listener}
NAVIDROME_LISTENER_PASSWORD=${NAVIDROME_LISTENER_PASSWORD:-$(genpw)}
NAVIDROME_MAIN_LIBRARY_ID=${NAVIDROME_MAIN_LIBRARY_ID:-1}
NAVIDROME_SAMPLES_LIBRARY_ID=${NAVIDROME_SAMPLES_LIBRARY_ID:-}
LIDARR_URL=$LD
LIDARR_API_KEY=${LIDARR_API_KEY:-}
LIDARR_UI_USER=${LIDARR_UI_USER:-admin}
LIDARR_UI_PASSWORD=${LIDARR_UI_PASSWORD:-$NAVIDROME_ADMIN_PASSWORD}

write_env() {
  umask 077
  cat > "$ENV_FILE" <<EOF
# Magpie dev stack credentials - generated by dev/bootstrap.sh. DEV ONLY. Do not commit.
NAVIDROME_URL=$NAVIDROME_URL
NAVIDROME_ADMIN_USER=$NAVIDROME_ADMIN_USER
NAVIDROME_ADMIN_PASSWORD=$NAVIDROME_ADMIN_PASSWORD
NAVIDROME_LISTENER_USER=$NAVIDROME_LISTENER_USER
NAVIDROME_LISTENER_PASSWORD=$NAVIDROME_LISTENER_PASSWORD
NAVIDROME_MAIN_LIBRARY_ID=$NAVIDROME_MAIN_LIBRARY_ID
NAVIDROME_SAMPLES_LIBRARY_ID=$NAVIDROME_SAMPLES_LIBRARY_ID
LIDARR_URL=$LIDARR_URL
LIDARR_API_KEY=$LIDARR_API_KEY
LIDARR_UI_USER=$LIDARR_UI_USER
LIDARR_UI_PASSWORD=$LIDARR_UI_PASSWORD
EOF
  chmod 600 "$ENV_FILE"
}
write_env   # persist generated passwords before anything can use them

# ------------------------------------------------------------------ fixtures + stack
say "Fixture library"
if [[ -z "$(find "$DEV_DIR/data/music/library" -type f \( -name '*.mp3' -o -name '*.flac' -o -name '*.m4a' \) 2>/dev/null | head -1)" ]]; then
  "$DEV_DIR/fixtures/make-library.sh"
else
  ok "dev/data/music already populated (run dev/fixtures/make-library.sh to fill gaps)"
fi
mkdir -p "$DEV_DIR/data/downloads/slskd" "$DEV_DIR/data/downloads/slskd-incomplete" "$DEV_DIR/data/music/samples"

say "Starting containers"
"${COMPOSE[@]}" up -d

wait_for() { # wait_for <name> <url> <seconds>
  local i
  for ((i = 0; i < $3; i++)); do curl -fsS -o /dev/null "$2" 2>/dev/null && { ok "$1 is up"; return 0; }; sleep 1; done
  die "$1 did not come up at $2 within $3 s (docker compose -f dev/docker-compose.yml logs $1)"
}
wait_for navidrome "$ND/ping" 120
wait_for lidarr "$LD/ping" 180

# ------------------------------------------------------------------ Navidrome
say "Navidrome"
json() { jq -nc "$@"; }
ndpost() { curl -sS -X "$1" "$ND$2" -H "x-nd-authorization: Bearer $NDTOKEN" -H 'Content-Type: application/json' ${3:+-d "$3"}; }

login_nd() { curl -sS -X POST "$ND/auth/login" -H 'Content-Type: application/json' \
  -d "$(json --arg u "$1" --arg p "$2" '{username:$u,password:$p}')"; }

# First run: no users exist yet -> createAdmin. Afterwards it returns an error and we just log in.
resp=$(curl -sS -X POST "$ND/auth/createAdmin" -H 'Content-Type: application/json' \
  -d "$(json --arg u "$NAVIDROME_ADMIN_USER" --arg p "$NAVIDROME_ADMIN_PASSWORD" '{username:$u,password:$p}')" || true)
if jq -e '.token' >/dev/null 2>&1 <<<"$resp"; then ok "created admin user '$NAVIDROME_ADMIN_USER'"; else ok "admin already exists"; fi
resp=$(login_nd "$NAVIDROME_ADMIN_USER" "$NAVIDROME_ADMIN_PASSWORD")
NDTOKEN=$(jq -r '.token // empty' <<<"$resp")
[[ -n "$NDTOKEN" ]] || die "cannot log in to Navidrome as $NAVIDROME_ADMIN_USER with the password in dev/.env.local. If the Navidrome volume predates this .env.local, run dev/reset.sh."
ND_SALT=$(jq -r .subsonicSalt <<<"$resp"); ND_TOK=$(jq -r .subsonicToken <<<"$resp")
SUBSONIC="u=$NAVIDROME_ADMIN_USER&t=$ND_TOK&s=$ND_SALT&v=1.16.1&c=magpie-bootstrap&f=json"

# Listener (normal user)
LISTENER_ID=$(ndpost GET /api/user | jq -r --arg u "$NAVIDROME_LISTENER_USER" '.[] | select(.userName==$u) | .id')
if [[ -z "$LISTENER_ID" ]]; then
  LISTENER_ID=$(ndpost POST /api/user "$(json --arg u "$NAVIDROME_LISTENER_USER" --arg p "$NAVIDROME_LISTENER_PASSWORD" \
    '{userName:$u,name:"Listener",password:$p,isAdmin:false}')" | jq -r '.id // empty')
  [[ -n "$LISTENER_ID" ]] || die "creating user $NAVIDROME_LISTENER_USER failed"
  ok "created user '$NAVIDROME_LISTENER_USER'"
else
  ok "user '$NAVIDROME_LISTENER_USER' exists"
fi

# Samples library (native API, Navidrome >= 0.58 multi-library; verified on 0.64.2)
libs=$(ndpost GET /api/library)
NAVIDROME_MAIN_LIBRARY_ID=$(jq -r '.[] | select(.path=="/music/library") | .id' <<<"$libs")
NAVIDROME_SAMPLES_LIBRARY_ID=$(jq -r '.[] | select(.path=="/music/samples") | .id' <<<"$libs")
if [[ -z "$NAVIDROME_SAMPLES_LIBRARY_ID" ]]; then
  NAVIDROME_SAMPLES_LIBRARY_ID=$(ndpost POST /api/library '{"name":"Samples","path":"/music/samples","defaultNewUsers":false}' | jq -r '.id // empty')
  [[ -n "$NAVIDROME_SAMPLES_LIBRARY_ID" ]] || die "POST /api/library failed"
  ok "created library 'Samples' (id $NAVIDROME_SAMPLES_LIBRARY_ID) at /music/samples"
else
  ok "library 'Samples' exists (id $NAVIDROME_SAMPLES_LIBRARY_ID)"
fi
write_env

# Listener gets both libraries (admins see all libraries automatically) + a scrobble filter that blocks
# Samples tracks from external scrobbling (spec section 8 / sandbox-samples.md section 3).
ndpost PUT "/api/user/$LISTENER_ID/library" \
  "$(json --argjson a "$NAVIDROME_MAIN_LIBRARY_ID" --argjson b "$NAVIDROME_SAMPLES_LIBRARY_ID" '{libraryIds:[$a,$b]}')" >/dev/null
ok "listener has libraries [$NAVIDROME_MAIN_LIBRARY_ID, $NAVIDROME_SAMPLES_LIBRARY_ID]"
filter=$(json --argjson b "$NAVIDROME_SAMPLES_LIBRARY_ID" '{all:[{is:{library_id:$b}}]}|tojson')
upd=$(ndpost GET "/api/user/$LISTENER_ID" | jq -c --argjson f "$filter" 'del(.libraries) | .scrobbleFilter=$f')
if ndpost PUT "/api/user/$LISTENER_ID" "$upd" | jq -e '.scrobbleFilter' >/dev/null 2>&1; then
  ok "listener scrobbleFilter excludes library $NAVIDROME_SAMPLES_LIBRARY_ID"
else
  warn "could not set listener scrobbleFilter"
fi

# Scan (incremental, all libraries) and wait for it to finish
curl -sS "$ND/rest/startScan?$SUBSONIC" >/dev/null
for i in $(seq 1 120); do
  st=$(curl -sS "$ND/rest/getScanStatus?$SUBSONIC" | jq -r '."subsonic-response".scanStatus.scanning')
  [[ "$st" == false ]] && break; sleep 1
done
ND_SONGS=$(curl -sS "$ND/rest/getScanStatus?$SUBSONIC" | jq -r '."subsonic-response".scanStatus.count')
ND_VERSION=$(curl -sS "$ND/rest/ping?$SUBSONIC" | jq -r '."subsonic-response".serverVersion')
ok "scan finished: $ND_SONGS songs (Navidrome $ND_VERSION)"

# ------------------------------------------------------------------ Lidarr
say "Lidarr"
for i in $(seq 1 30); do
  LIDARR_API_KEY=$("${COMPOSE[@]}" exec -T lidarr cat /config/config.xml 2>/dev/null | sed -n 's:.*<ApiKey>\(.*\)</ApiKey>.*:\1:p' || true)
  [[ -n "$LIDARR_API_KEY" ]] && break; sleep 1
done
[[ -n "$LIDARR_API_KEY" ]] || die "could not read ApiKey from Lidarr /config/config.xml"
write_env
ok "API key read from /config/config.xml"
lget() { curl -sS -H "X-Api-Key: $LIDARR_API_KEY" "$LD/api/v1$1"; }
lsend() { curl -sS -X "$1" -H "X-Api-Key: $LIDARR_API_KEY" -H 'Content-Type: application/json' "$LD/api/v1$2" -d "$3"; }
for i in $(seq 1 60); do lget /system/status | jq -e .version >/dev/null 2>&1 && break; sleep 1; done
LIDARR_VERSION=$(lget /system/status | jq -r .version)
ok "Lidarr $LIDARR_VERSION"

# UI login (Lidarr v3 requires auth; API uses the key). Forms auth with the generated password.
host=$(lget /config/host)
if [[ $(jq -r .authenticationMethod <<<"$host") != forms ]]; then
  lsend PUT /config/host/1 "$(jq -c --arg u "$LIDARR_UI_USER" --arg p "$LIDARR_UI_PASSWORD" \
    '.authenticationMethod="forms" | .authenticationRequired="enabled" | .username=$u | .password=$p
     | .passwordConfirmation=$p | .analyticsEnabled=false | .logLevel="info"' <<<"$host")" >/dev/null
  ok "UI forms login set: $LIDARR_UI_USER / (LIDARR_UI_PASSWORD)"
else
  ok "UI forms login already configured"
fi

# Root folders
QP=$(lget /qualityprofile | jq -r '[.[] | select(.name=="Lossless")][0].id // .[0].id')
MP=$(lget /metadataprofile | jq -r '[.[] | select(.name=="Standard")][0].id // .[0].id')
roots=$(lget /rootfolder)
add_root() { # add_root <name> <path>
  if jq -e --arg p "$2" '.[] | select(.path==$p or .path==($p+"/"))' >/dev/null <<<"$roots"; then ok "root folder $2 exists"; return; fi
  r=$(lsend POST /rootfolder "$(json --arg n "$1" --arg p "$2" --argjson q "$QP" --argjson m "$MP" \
    '{name:$n,path:$p,defaultQualityProfileId:$q,defaultMetadataProfileId:$m,defaultMonitorOption:"all",defaultNewItemMonitorOption:"all",defaultTags:[]}')")
  jq -e .id >/dev/null <<<"$r" && ok "root folder $2 created" || warn "root folder $2: $r"
}
add_root "Music Library" /music/library
add_root "Samples" /music/samples

# Subsonic connection -> Navidrome (Lidarr calls startScan on import/upgrade/rename/retag)
if lget /notification | jq -e '.[] | select(.implementation=="Subsonic")' >/dev/null; then
  ok "Subsonic connection exists"
else
  r=$(lsend POST /notification "$(json --arg u "$NAVIDROME_ADMIN_USER" --arg p "$NAVIDROME_ADMIN_PASSWORD" '{
      name:"Navidrome", implementation:"Subsonic", configContract:"SubsonicSettings",
      onReleaseImport:true, onUpgrade:true, onRename:true, onTrackRetag:true, tags:[],
      fields:[{name:"host",value:"navidrome"},{name:"port",value:4533},{name:"urlBase",value:""},
              {name:"username",value:$u},{name:"password",value:$p},{name:"notify",value:false},
              {name:"updateLibrary",value:true},{name:"useSsl",value:false}]}')")
  jq -e .id >/dev/null <<<"$r" && ok "Subsonic connection -> http://navidrome:4533 created (connection test passed)" \
                              || warn "Subsonic connection failed: $(jq -c . <<<"$r" | cut -c1-300)"
fi

# Track renaming + tag writing (spec section 13 "fast lane traps": setup enables these)
lsend PUT /config/naming/1 "$(lget /config/naming | jq -c '.renameTracks=true')" >/dev/null && ok "track renaming on"
lsend PUT /config/metadataprovider/1 "$(lget /config/metadataprovider | jq -c '.writeAudioTags="newFiles"')" >/dev/null && ok "audio tag writing: new files"

write_env

# ------------------------------------------------------------------ summary
ROOTS=$(lget /rootfolder | jq -r '[.[].path] | join(", ")')
cat <<EOF

$(printf '\033[1mMagpie dev stack is up\033[0m')
  Navidrome $ND_VERSION   $ND        admin: $NAVIDROME_ADMIN_USER   listener: $NAVIDROME_LISTENER_USER
     libraries: $NAVIDROME_MAIN_LIBRARY_ID=/music/library  $NAVIDROME_SAMPLES_LIBRARY_ID=/music/samples (Samples)   songs: $ND_SONGS
  Lidarr $LIDARR_VERSION   $LD        UI login: $LIDARR_UI_USER   root folders: $ROOTS
  Credentials + Lidarr API key: dev/.env.local
  Next: dev/smoke.sh
EOF
